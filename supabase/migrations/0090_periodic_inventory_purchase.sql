-- M59 สินค้าคงเหลือแบบสิ้นงวด (periodic) ตาม FA — เจ้าของระบบสั่ง 16-11-2026 "เอาตาม FA ทั้งหมด"
-- ใบรับสินค้า (RI ทุกเส้นทาง: บันทึก/แก้ไข/แยกจาก PO) ลง Dr 51111.01 ซื้อสินค้า แทน Dr 11500 สินค้าคงเหลือ
-- (เดิม: ซื้อเข้าสินค้าคงเหลือ แต่ขายไม่ลงต้นทุน → กำไรสูงเกินจริง) · ขายยังไม่ลงต้นทุนตาม M12
-- สต็อกย่อย (จำนวน/มูลค่า/ต้นทุนเฉลี่ย) ทำงานเหมือนเดิม · ยอดสินค้าคงเหลือในงบดุลให้นักบัญชีปรับปรุงปลายงวด
-- ทุกฟังก์ชัน RI เรียก sys_account('inventory') จึงเปลี่ยนที่การตั้งค่าบัญชีระบบจุดเดียว (คีย์ inventory = "บัญชีที่ลงตอนรับสินค้า")
-- ใบสำคัญเก่าที่ลง 11500 ไว้แล้วไม่ถูกแก้ (แก้ใบสำคัญไม่ได้) — ถ้ามีข้อมูลจริงให้โอนยอดด้วย JV
insert into accounts(code, name, type)
select '51111.01', 'ซื้อสินค้า', 'expense'
 where not exists (select 1 from accounts where code = '51111.01');
update system_accounts set account_code = '51111.01',
       note = 'บัญชีที่ลงตอนรับสินค้า (RI) — ซื้อสินค้า ตาม FA (สินค้าคงเหลือแบบสิ้นงวด)'
 where key = 'inventory';
